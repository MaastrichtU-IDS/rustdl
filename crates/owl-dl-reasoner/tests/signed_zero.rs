#[test]
fn distinct_zeros_do_not_clash() {
    for (what, body) in [
        (
            "s_min2_facet00_d",
            "SubClassOf(:C DataMinCardinality(2 :d DatatypeRestriction(xsd:double xsd:minInclusive \"0.0\"^^xsd:double xsd:maxInclusive \"0.0\"^^xsd:double)))",
        ),
        (
            "s_neghv_d",
            "SubClassOf(:C ObjectIntersectionOf(DataHasValue(:d \"-0.0\"^^xsd:double) ObjectComplementOf(DataHasValue(:d \"0.0\"^^xsd:double))))",
        ),
        (
            "s_all_ge0_d",
            "SubClassOf(:C ObjectIntersectionOf(DataHasValue(:d \"-0.0\"^^xsd:double) DataAllValuesFrom(:d DatatypeRestriction(xsd:double xsd:minInclusive \"0.0\"^^xsd:double))))",
        ),
        (
            "s_min2_facet00_f",
            "SubClassOf(:C DataMinCardinality(2 :d DatatypeRestriction(xsd:float xsd:minInclusive \"0.0\"^^xsd:float xsd:maxInclusive \"0.0\"^^xsd:float)))",
        ),
        (
            "s_neghv_f",
            "SubClassOf(:C ObjectIntersectionOf(DataHasValue(:d \"-0.0\"^^xsd:float) ObjectComplementOf(DataHasValue(:d \"0.0\"^^xsd:float))))",
        ),
        (
            "s_all_ge0_f",
            "SubClassOf(:C ObjectIntersectionOf(DataHasValue(:d \"-0.0\"^^xsd:float) DataAllValuesFrom(:d DatatypeRestriction(xsd:float xsd:minInclusive \"0.0\"^^xsd:float))))",
        ),
    ] {
        assert!(c_sat(body), "{what}: C satisfiable (HermiT)");
    }
    for (what, body) in [
        (
            "c_ndpa_d",
            "DataPropertyAssertion(:d :a \"-0.0\"^^xsd:double) NegativeDataPropertyAssertion(:d :a \"0.0\"^^xsd:double)",
        ),
        (
            "c_disjdp_d",
            "DisjointDataProperties(:d :e) DataPropertyAssertion(:d :a \"0.0\"^^xsd:double) DataPropertyAssertion(:e :a \"-0.0\"^^xsd:double)",
        ),
        (
            "c_all_pos_d",
            "DataPropertyAssertion(:d :a \"0.0\"^^xsd:double) ClassAssertion(DataAllValuesFrom(:d DataOneOf(\"0.0\"^^xsd:double)) :a)",
        ),
        (
            "c_ndpa_f",
            "DataPropertyAssertion(:d :a \"-0.0\"^^xsd:float) NegativeDataPropertyAssertion(:d :a \"0.0\"^^xsd:float)",
        ),
        (
            "c_disjdp_f",
            "DisjointDataProperties(:d :e) DataPropertyAssertion(:d :a \"0.0\"^^xsd:float) DataPropertyAssertion(:e :a \"-0.0\"^^xsd:float)",
        ),
        (
            "c_all_pos_f",
            "DataPropertyAssertion(:d :a \"0.0\"^^xsd:float) ClassAssertion(DataAllValuesFrom(:d DataOneOf(\"0.0\"^^xsd:float)) :a)",
        ),
    ] {
        assert!(consistent(body), "{what}: consistent (HermiT)");
    }
    // Control: the SAME zero on two disjoint properties does clash.
    for (what, body) in [
        (
            "c_disjdp_ctl_d",
            "DisjointDataProperties(:d :e) DataPropertyAssertion(:d :a \"0.0\"^^xsd:double) DataPropertyAssertion(:e :a \"0.0\"^^xsd:double)",
        ),
        (
            "c_disjdp_ctl_f",
            "DisjointDataProperties(:d :e) DataPropertyAssertion(:d :a \"0.0\"^^xsd:float) DataPropertyAssertion(:e :a \"0.0\"^^xsd:float)",
        ),
    ] {
        assert!(!consistent(body), "{what}: inconsistent (HermiT)");
    }
}

