//! #590: signed zero in `xsd:float` / `xsd:double`. OWL 2 (Structural Specification
//! §4.2) reads a literal VALUE by identity, where `-0` and `+0` are distinct, and a
//! FACET by equality, where they are equal: the facet range `[0, 0]` holds both zeros.
//! rustdl collapsed the zeros everywhere, which gave false subsumptions
//! (`hasValue(-0) ⊑ hasValue(+0)`, `∃d.[0, 0] ⊑ hasValue(+0)`), false unsats
//! (`≥2 d.[0, 0]`, `hasValue(-0) ⊓ ¬hasValue(+0)`) and false inconsistencies (a negative
//! assertion of the other zero, `DisjointDataProperties` with one zero each).
//!
//! Every case is a probe in `~/rustdl/sweeps/wB/590/p3/` (generated by `cases.py`), and
//! `HermiT` gives the verdict asserted here (`hermit.out`). Each case runs in both
//! `xsd:double` (`_d`) and `xsd:float` (`_f`). Negatives come first. The residuals at
//! the end pin rustdl's documented divergences from the specification. `n_hv_rev_f` is
//! the `dz_float` canary from the #589 review.

#![allow(clippy::unwrap_used)]

use horned_owl::io::ParserConfiguration;
use horned_owl::io::ofn::reader::read as read_ofn;
use horned_owl::model::RcStr;
use horned_owl::ontology::set::SetOntology;
use std::io::Cursor;

const EX: &str = "http://ex.org/t#";

fn onto(body: &str) -> SetOntology<RcStr> {
    let src = format!(
        "Prefix(:=<{EX}>)\nPrefix(xsd:=<http://www.w3.org/2001/XMLSchema#>)\n\
         Ontology(<http://ex.org/t>\n\
         Declaration(DataProperty(:d)) Declaration(DataProperty(:e))\n\
         Declaration(Class(:C)) Declaration(Class(:E)) Declaration(NamedIndividual(:a))\n\
         {body}\n)\n"
    );
    read_ofn(&mut Cursor::new(src), ParserConfiguration::default())
        .unwrap()
        .0
}

/// `C ⊑ E` through `subclass` and through `classify`, which must agree.
fn c_sub_e(what: &str, body: &str) -> bool {
    let o = onto(body);
    let pair = owl_dl_reasoner::is_subclass_of(&o, &format!("{EX}C"), &format!("{EX}E")).unwrap();
    let c = owl_dl_reasoner::classify(&o).unwrap();
    assert_eq!(
        pair,
        c.is_subclass(&format!("{EX}C"), &format!("{EX}E")),
        "{what}: subclass and classify disagree"
    );
    pair
}

fn c_sat(body: &str) -> bool {
    owl_dl_reasoner::is_class_satisfiable(&onto(body), &format!("{EX}C")).unwrap()
}

fn consistent(body: &str) -> bool {
    owl_dl_reasoner::is_consistent(&onto(body)).unwrap()
}

