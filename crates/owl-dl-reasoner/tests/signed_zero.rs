/// Every surface that trusts the saturator withholds the guarantee when the `DKey`s
/// tell the zeros apart (#590 review: `realize_saturation_eligible` read
/// `saturator_complete_fragment`, which lacked the check, so an instance query
/// returned `[]` with the guarantee set). Both arms of `has_signed_zero_split` are
/// exercised: the `[0, 0]` range and a `-0` enumeration member.
#[test]
fn the_guarantee_is_withheld_on_every_surface() {
    use horned_owl::model::{Build, ClassExpression};
    let split = format!("{} ClassAssertion(:C :a)", cases_body("r_case_split_d"));
    let o = onto(&split);
    assert!(
        !owl_dl_reasoner::classify(&o)
            .unwrap()
            .completeness_guaranteed(),
        "classify"
    );
    let (_, stats) =
        owl_dl_reasoner::is_subclass_of_with_stats(&o, &format!("{EX}C"), &format!("{EX}E"))
            .unwrap();
    assert!(!stats.completeness_guaranteed(), "per-pair subclass");
    let e: ClassExpression<RcStr> = ClassExpression::Class(Build::new_rc().class(format!("{EX}E")));
    let inst = owl_dl_reasoner::class_expression_instances(&o, &e).unwrap();
    assert!(
        !inst.completeness_guaranteed(),
        "instance query: {:?}",
        inst.individuals()
    );
    let r = owl_dl_reasoner::realize(&o).unwrap();
    assert!(
        r.witness_prune_active() || r.incomplete(),
        "realize signals its prune"
    );
    // The enumeration arm: `C ⊑ ∃d.{-0, 2}`.
    let oneof = onto(
        "SubClassOf(:C DataSomeValuesFrom(:d DataOneOf(\"-0.0\"^^xsd:double \"2.0\"^^xsd:double)))",
    );
    assert!(
        !owl_dl_reasoner::classify(&oneof)
            .unwrap()
            .completeness_guaranteed(),
        "enumeration with -0"
    );
}
